// Joins the reminder function's two source files into the single index.ts the
// Supabase dashboard editor expects, so it can be pasted in one go.
import { readFileSync, writeFileSync } from 'node:fs';

const dir = new URL('../supabase/functions/send-reminders/', import.meta.url);
const logic = readFileSync(new URL('src/logic.ts', dir), 'utf8');
const handler = readFileSync(new URL('src/handler.ts', dir), 'utf8').replace(/^import .* from '\.\/logic\.ts';\n/m, '');

const imports = handler.match(/^import .*;$/gm) ?? [];
const handlerBody = handler.replace(/^import .*;\n/gm, '');

const out = `// Herd reminders: Supabase Edge Function "send-reminders".
// GENERATED by "npm run build:function" from src/logic.ts and src/handler.ts.
// Paste this whole file into the Supabase function editor.

${imports.join('\n')}

// ---------------------------------------------------------------------------
// Reminder rules
// ---------------------------------------------------------------------------

${logic.trim()}

// ---------------------------------------------------------------------------
// Request handler
// ---------------------------------------------------------------------------
${handlerBody.trimEnd()}
`;
writeFileSync(new URL('index.ts', dir), out);
console.log('built supabase/functions/send-reminders/index.ts');
